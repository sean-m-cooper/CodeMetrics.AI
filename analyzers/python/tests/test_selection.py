class SelectionTests(unittest.TestCase):
    def tree(self, files, **options):
        with tempfile.TemporaryDirectory() as directory:
            root = Path(directory)
            for name, source in files.items():
                path = root / name
                path.parent.mkdir(parents=True, exist_ok=True)
                path.write_text(source, encoding="utf-8")
            return facts.analyze(root, **options)

    def test_default_roles_and_exclusion_provenance(self):
        document = self.tree({
            "pkg/code.py": "def keep(): pass", "tests/test_work.py": "def test_work(): pass",
            "pkg/test_work.py": "def helper(): pass", "conftest.py": "def fixture(): pass",
            "docs/conf.py": "def setup(): pass", "pkg/code.pyi": "invalid stub syntax is not parsed",
            "pkg/generated.py": "# Generated by tool. DO NOT EDIT!\ndef generated(): pass",
            ".venv/broken.py": "invalid syntax", "pkg/testing.py": "def runtime_helper(): pass",
        })
        self.assertEqual(document["status"], "complete")
        self.assertEqual({row["member"] for row in document["functions"]}, {"keep", "runtime_helper"})
        self.assertEqual(len(document["selection"]["files"]), 8)
        self.assertEqual(document["selection"]["prunedDirectories"][0]["path"], ".venv")
        excluded = {row["category"] for row in document["selection"]["files"] if row["disposition"] == "excluded"}
        self.assertEqual(excluded, {"test", "support", "declaration", "generated"})

    def test_explicit_inclusion_keeps_roles_and_exclusion_wins(self):
        document = self.tree({"a.py": "def a(): pass", "tests/test_b.py": "def b(): pass",
                              "examples/c.py": "def c(): pass", "g.py": "# Generated by tool\ndef g(): pass"},
                             include_tests=True, include_support=True, include_generated=True, exclude=["a.py"])
        self.assertEqual({row["member"]: row["population"] for row in document["functions"]}, {"b": "test", "c": "support", "g": "generated"})
        self.assertEqual(document["selection"]["files"][0]["reason"], "explicit-exclusion")

    def test_path_overrides_handle_public_testing_helpers(self):
        document = self.tree({"framework/test/client.py": "def client(): pass", "checks/verify.py": "def verify(): pass"},
                             production_paths=["framework/test/**"], test_paths=["checks/**"])
        self.assertEqual([row["member"] for row in document["functions"]], ["client"])
        self.assertEqual(document["functions"][0]["population"], "production")

    def test_includes_are_explicit_and_outside_errors_do_not_fail_scope(self):
        document = self.tree({"pkg/good.py": "def good(): pass", "other/bad.py": "def ("}, include=["pkg/**"])
        self.assertEqual(document["status"], "complete")
        self.assertEqual(len(document["functions"]), 1)
        failed = self.tree({"tests/test_bad.py": "def ("}, include_tests=True)
        self.assertEqual(failed["status"], "incomplete")
        self.assertEqual(failed["selection"]["files"][0]["disposition"], "failed")

    def test_generated_markers_require_comments_and_allow_override(self):
        document = self.tree({"text.py": 'message = "# Generated by tool"\ndef keep(): pass',
                              "docstring.py": '"""Description\n# Generated by tool\n"""\ndef keep_docstring(): pass',
                              "late.py": "\n" * 20 + "# Generated by tool\ndef also_keep(): pass"})
        self.assertEqual(len(document["functions"]), 3)
        result = self.tree({"marked.py": "# Automatically generated\ninvalid syntax"}, include_generated=True)
        self.assertEqual(result["status"], "incomplete")

    def test_configuration_fingerprint_is_order_independent_but_sensitive(self):
        files = {"a.py": "def a(): pass"}
        first = self.tree(files, include=["**/*.py", "a.py"])
        second = self.tree(files, include=["a.py", "**/*.py", "a.py"])
        self.assertEqual(first, second)
        third = self.tree(files, include_tests=True)
        self.assertNotEqual(first["selection"]["configurationFingerprint"], third["selection"]["configurationFingerprint"])
        self.assertEqual(len(first["functions"]), 1)

    def test_invalid_selection_is_incomplete(self):
        for pattern in ("", "../other/**", "/absolute", "C:/code", "pkg\\code.py"):
            with self.subTest(pattern=pattern):
                with self.assertRaises(ValueError):
                    selection_options(include=[pattern])
                self.assertEqual(self.tree({}, include=[pattern])["status"], "incomplete")

    def test_cli_flags_match_the_api_and_declarations_never_get_credit(self):
        with tempfile.TemporaryDirectory() as temporary:
            path = Path(temporary) / "test_worker.py"
            path.write_text("from typing import overload\n@overload\ndef work(x): ...\ndef work(x): return x\n")
            command = [sys.executable, str(Path(facts.__file__)), str(path)]
            default = subprocess.run(command, capture_output=True, text=True)
            self.assertEqual(default.returncode, 0)
            self.assertEqual(json.loads(default.stdout)["functions"], [])
            included = subprocess.run(command + ["--include-tests", "--include", "**/*.py"], capture_output=True, text=True)
            self.assertEqual(included.returncode, 0)
            document = json.loads(included.stdout)
            self.assertEqual(len(document["functions"]), 1)
            self.assertEqual(document["functions"][0]["population"], "test")
            self.assertEqual(len(document["selection"]["excludedFunctions"]), 1)


class DeclarationTests(unittest.TestCase):
    def collect(self, source):
        tree = ast.parse(source)
        collector = facts.Functions("code.py", tree)
        collector.visit(tree)
        return collector

    def test_only_verified_placeholder_declarations_are_removed(self):
        result = self.collect('''
from typing import overload as signature, Protocol
from abc import abstractmethod
@signature
def convert(value: str): ...
def convert(value): return value
class Interface(Protocol):
    def required(self): "Required operation."
    def default(self): return 1
class Base:
    @abstractmethod
    async def empty(self): pass
    @abstractmethod
    def implemented(self): return 1
def intentional_noop(): pass
def undocumented_ellipsis(): ...
''')
        self.assertEqual([row["reason"] for row in result.excluded_functions], ["overload-declaration", "protocol-declaration", "abstract-declaration"])
        self.assertEqual({row["member"] for row in result.functions}, {"convert", "Interface.default", "Base.implemented", "intentional_noop", "undocumented_ellipsis"})

    def test_qualified_aliases_and_generic_protocols(self):
        result = self.collect('''
import typing as t
import abc as a
class Interface(t.Protocol[T]):
    def declared(self): ...
@t.overload
def choice(x): ...
class Base:
    @a.abstractmethod
    def declared(self): pass
''')
        self.assertEqual(len(result.excluded_functions), 3)

    def test_shadowed_aliases_are_retained(self):
        prefixes = ["overload = custom", "def elsewhere(overload): pass", "from custom import overload",
                    "from custom import *", "for overload in values: pass", "del overload"]
        for prefix in prefixes:
            with self.subTest(prefix=prefix):
                result = self.collect(f"from typing import overload\n{prefix}\n@overload\ndef choice(x): ...")
                self.assertEqual(result.excluded_functions, [])

    def test_custom_decorators_and_real_abstract_implementations_remain(self):
        result = self.collect('''
from custom import abstractmethod, overload
@abstractmethod
def required(): pass
@overload
def signature(): ...
''')
        self.assertEqual(len(result.functions), 2)
        self.assertEqual(result.excluded_functions, [])

    def test_protocol_context_does_not_leak_into_nested_implementations(self):
        result = self.collect('''
from typing import Protocol
class API(Protocol):
    def implemented(self):
        def nested(): ...
        class Inner:
            def method(self): pass
        return nested
''')
        self.assertEqual(len(result.functions), 3)
        self.assertEqual(result.excluded_functions, [])



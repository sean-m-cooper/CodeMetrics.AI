"""Deterministic, overridable selection. These categories are scope, not defects."""

import ast
from fnmatch import fnmatchcase
import hashlib
import io
import json
from pathlib import PurePosixPath
import re
import tokenize


POLICY = "python/source-selection-v1"
GENERATED = re.compile(r"^\s*#\s*(?:generated by\b|this file (?:is|was) (?:automatically )?generated\b|automatically generated\b|code generated\b)", re.I)


def matches(file, patterns):
    for pattern in patterns:
        if fnmatchcase(file, pattern):
            return True
        while pattern.startswith("**/"):
            pattern = pattern[3:]
            if fnmatchcase(file, pattern):
                return True
    return False


def selection_options(include=(), exclude=(), test_paths=(), production_paths=(), include_tests=False, include_generated=False, include_support=False):
    options = {
        "include": sorted(set(include)), "exclude": sorted(set(exclude)),
        "testPaths": sorted(set(test_paths)), "productionPaths": sorted(set(production_paths)),
        "includeTests": include_tests, "includeGenerated": include_generated, "includeSupport": include_support,
    }
    for key in ("include", "exclude", "testPaths", "productionPaths"):
        for pattern in options[key]:
            if not pattern or "\\" in pattern or pattern.startswith("/") or ":" in pattern or ".." in pattern.split("/"):
                raise ValueError("Selection patterns must be nonempty root-relative POSIX patterns without '..'.")
    return options


def inventory(options):
    fingerprint = hashlib.sha256(json.dumps({"policy": POLICY, "options": options}, sort_keys=True, separators=(",", ":")).encode()).hexdigest()
    return {"policy": POLICY, "configurationFingerprint": fingerprint, "options": options,
            "files": [], "prunedDirectories": [], "excludedFunctions": []}


def category(file, options):
    path = PurePosixPath(file)
    if path.suffix == ".pyi":
        return "declaration", "stub-file"
    if matches(file, options["productionPaths"]):
        return "production", "explicit-production-path"
    if matches(file, options["testPaths"]):
        return "test", "explicit-test-path"
    if any(part in {"test", "tests"} for part in path.parts[:-1]) or path.name == "conftest.py" or path.name.startswith("test_") or path.name.endswith("_test.py"):
        return "test", "test-path-convention"
    if any(part in {"docs", "doc", "examples", "benchmarks"} for part in path.parts[:-1]) or file in {"setup.py", "noxfile.py"}:
        return "support", "support-path-convention"
    return "production", "production-candidate"


def file_record(file, options):
    kind, reason = category(file, options)
    disposition = "analyzed"
    if options["include"] and not matches(file, options["include"]):
        disposition, reason = "excluded", "outside-include-selection"
    elif matches(file, options["exclude"]):
        disposition, reason = "excluded", "explicit-exclusion"
    elif kind == "declaration" or (kind == "test" and not options["includeTests"]) or (kind == "support" and not options["includeSupport"]):
        disposition = "excluded"
    return {"file": file, "category": kind, "disposition": disposition, "reason": reason, "contentSha256": None}


def generated_source(source):
    try:
        for token in tokenize.generate_tokens(io.StringIO(source).readline):
            if token.start[0] > 20:
                break
            if token.type == tokenize.COMMENT and GENERATED.match(token.string):
                return True
    except (tokenize.TokenError, IndentationError):
        pass  # The AST parser will report malformed selected source.
    return False


def bound_names(node):
    """Conservative whole-file shadow check; uncertainty keeps implementations in scope."""
    names = set()
    for child in ast.walk(node):
        if isinstance(child, ast.Name) and isinstance(child.ctx, (ast.Store, ast.Del)):
            names.add(child.id)
        elif isinstance(child, ast.arg):
            names.add(child.arg)
        elif isinstance(child, (ast.FunctionDef, ast.AsyncFunctionDef, ast.ClassDef)):
            names.add(child.name)
        elif isinstance(child, ast.ExceptHandler) and child.name:
            names.add(child.name)
        elif isinstance(child, (ast.MatchAs, ast.MatchStar)) and child.name:
            names.add(child.name)
        elif isinstance(child, ast.MatchMapping) and child.rest:
            names.add(child.rest)
        elif isinstance(child, (ast.Attribute, ast.Subscript)) and isinstance(child.ctx, (ast.Store, ast.Del)):
            base = child.value
            while isinstance(base, (ast.Attribute, ast.Subscript)):
                base = base.value
            if isinstance(base, ast.Name):
                names.add(base.id)
    return names


def import_bindings(tree):
    bindings, seen = {}, {}
    top_level = {id(node) for node in tree.body}
    for node in ast.walk(tree):
        pairs = []
        if isinstance(node, ast.Import):
            pairs = [(item.asname or item.name.split(".")[0], item.name if item.asname else item.name.split(".")[0]) for item in node.names]
        elif isinstance(node, ast.ImportFrom):
            pairs = [(item.asname or item.name, f"{node.module}.{item.name}" if not node.level else "<relative>") for item in node.names]
        for name, target in pairs:
            seen.setdefault(name, set()).add(target)
            if id(node) in top_level:
                bindings[name] = target
    blocked = bound_names(tree)
    if "*" in seen:
        return {}
    return {name: target for name, target in bindings.items() if name not in blocked and seen[name] == {target}}


def resolve(node, bindings):
    if isinstance(node, ast.Subscript):
        return resolve(node.value, bindings)
    if isinstance(node, ast.Name):
        return bindings.get(node.id)
    if isinstance(node, ast.Attribute):
        owner = resolve(node.value, bindings)
        return f"{owner}.{node.attr}" if owner else None
    return None


def declaration_reason(node, bindings, protocol_method=False):
    if isinstance(node, ast.Lambda):
        return None
    body = node.body
    if body and isinstance(body[0], ast.Expr) and isinstance(body[0].value, ast.Constant) and isinstance(body[0].value.value, str):
        body = body[1:]
    placeholder = all(isinstance(item, ast.Pass) or (isinstance(item, ast.Expr) and isinstance(item.value, ast.Constant) and item.value.value is Ellipsis) for item in body)
    if not placeholder:
        return None
    decorators = {resolve(item, bindings) for item in node.decorator_list}
    if decorators & {"typing.overload", "typing_extensions.overload"}:
        return "overload-declaration"
    if "abc.abstractmethod" in decorators:
        return "abstract-declaration"
    if protocol_method:
        return "protocol-declaration"
    return None
